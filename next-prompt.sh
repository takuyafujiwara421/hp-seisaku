#!/bin/bash
# 内装カット用のプロンプトを1つずつクリップボードに入れる
#
#   ./next-prompt.sh        次のプロンプトをコピー
#   ./next-prompt.sh 2      2番目をコピー
#   ./next-prompt.sh reset  最初に戻す
#   ./next-prompt.sh list   一覧を見る
#
# Gemini で cmd+v → Enter するだけで済むようにするための道具。

DIR="$(cd "$(dirname "$0")" && pwd)"
STATE="$DIR/.prompt-state"

NAMES=(
  "04-doma｜土間のある広い玄関"
  "05-laundry｜ランドリールーム（家事室）"
  "06-nook｜ヌック（こもれる小空間）"
  "07-workspace｜造作ワークスペース"
)

P1='日本の新築住宅の広い土間のある玄関の内観を、プロのインテリア写真家が撮影したような高品質な実写写真で生成してください。モルタル仕上げの土間が広く取られ、壁面には木の造作棚、ベビーカーと自転車が1台ずつ置かれています。奥に室内へ上がる木の段差。大きな窓から明るい自然光が差し込む。人物は写さないでください。文字・ロゴは一切入れないでください。横長16:9。'
P2='日本の新築住宅のランドリールーム（家事室）の内観を、プロのインテリア写真家が撮影したような高品質な実写写真で生成してください。洗濯機と乾燥機、室内物干しバー、作業カウンター、木の収納棚が一室にまとまっています。白とライトグレーを基調に、木の質感を効かせた清潔感のある空間。窓から柔らかい自然光。人物は写さないでください。文字・ロゴは一切入れないでください。横長16:9。'
P3='日本の新築住宅のリビングの一角にある小上がりのヌック（こもれる小さな空間）の内観を、プロのインテリア写真家が撮影したような高品質な実写写真で生成してください。一段上がった床に造作のベンチとクッション、壁面には本棚、小さな窓から外の緑が見えます。木の温かみのある落ち着いた空間。人物は写さないでください。文字・ロゴは一切入れないでください。横長16:9。'
P4='日本の新築住宅にある造作カウンターのワークスペースの内観を、プロのインテリア写真家が撮影したような高品質な実写写真で生成してください。壁面に一枚板の木製カウンターを造り付け、その上にノートパソコンと観葉植物、上部には本棚。窓に面していて自然光が入ります。落ち着いた色調で生活感を抑えた空間。人物は写さないでください。文字・ロゴは一切入れないでください。横長16:9。'

get_prompt() {
  case "$1" in
    1) printf '%s' "$P1" ;;
    2) printf '%s' "$P2" ;;
    3) printf '%s' "$P3" ;;
    4) printf '%s' "$P4" ;;
  esac
}

case "${1:-next}" in
  list)
    echo "内装カットのプロンプト一覧:"
    i=1
    for n in "${NAMES[@]}"; do echo "  $i. $n"; i=$((i+1)); done
    [ -f "$STATE" ] && echo "（次にコピーされるのは $(( $(cat "$STATE") + 1 )) 番）"
    exit 0 ;;
  reset)
    rm -f "$STATE"; echo "最初に戻しました。次は 1番です。"; exit 0 ;;
  [1-4])
    N="$1" ;;
  next)
    DONE=0; [ -f "$STATE" ] && DONE=$(cat "$STATE")
    N=$((DONE + 1))
    if [ "$N" -gt 4 ]; then
      echo "4つとも配り終えました。やり直すなら ./next-prompt.sh reset"
      exit 0
    fi
    echo "$N" > "$STATE" ;;
  *)
    echo "使い方: ./next-prompt.sh [next|1-4|list|reset]"; exit 1 ;;
esac

get_prompt "$N" | pbcopy
echo "コピーしました → ${NAMES[$((N-1))]}"
echo
echo "  1. Gemini で「新しいチャット」を開く（★1枚ごとに新規チャット）"
echo "  2. 入力欄に cmd+v → Enter"
echo "  3. 30〜50秒待つ → 画像の右上「↓」で ~/Downloads に保存"
echo
if [ "$N" -lt 4 ]; then
  echo "次の1枚は ./next-prompt.sh"
else
  echo "4枚そろったら:"
  echo "  ./add-images.sh 04-doma 05-laundry 06-nook 07-workspace"
fi
